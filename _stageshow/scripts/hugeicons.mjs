// Writes src/ko-icons.ts: the Hugeicons (free, stroke rounded, MIT; see
// LICENSE-hugeicons) that Kora's scenes draw, the same glyphs Kora compiles
// into its own symbols. Run it with the unpacked @hugeicons/core-free-icons
// package when the list below changes:
//
//   node scripts/hugeicons.mjs /path/to/core-free-icons/package
//
// The package's files are read as text, never run.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const NAMES = [
  // Sidebar
  'Images', 'Clock01', 'Favourite', 'Tag02', 'MessageNotification01', 'Delete02',
  'Layers01', 'Calendar03', 'UserMultiple', 'Building03', 'Tag01', 'TimelineList',
  'BookOpen01', 'GalleryThumbnails', 'FileChartColumn', 'FileExport', 'Settings01', 'SidebarLeft',
  // Toolbar and status bar
  'GridView', 'LeftToRightListBullet', 'ArrowUpDown', 'FilterHorizontal', 'TimeHalfPass',
  'Download04', 'SidebarRight', 'Search01', 'ArrowDown01', 'Grid3x3', 'Tick02', 'CancelCircle',
  // History
  'PencilEdit02',
  // Finder
  'Folder01',
]

const root = process.argv[2]
if (!root) {
  console.error('Usage: node scripts/hugeicons.mjs <path to the core-free-icons package>')
  process.exit(2)
}

const out = {}
for (const name of NAMES) {
  const text = readFileSync(join(root, 'dist/esm', `${name}Icon.js`), 'utf8')
  const body = text.slice(text.indexOf('['), text.lastIndexOf('];') + 1)
  // The file is an array literal of [tag, { attr: "value" }] pairs: quote the keys to read it as JSON.
  const json = body.replace(/([{,]\s*)([A-Za-z]+):/g, '$1"$2":')
  out[name] = JSON.parse(json).map(([tag, attrs]) => {
    const { key, ...rest } = attrs
    return [tag, rest]
  })
}

const lines = Object.entries(out).map(([name, els]) => `  ${name}: ${JSON.stringify(els)},`)
writeFileSync(
  new URL('../src/ko-icons.ts', import.meta.url),
  `// Generated by scripts/hugeicons.mjs from @hugeicons/core-free-icons (MIT,
// see LICENSE-hugeicons). Each icon is a 24×24 stroke drawing in currentColor.
export const HUGEICONS = {
${lines.join('\n')}
} as const satisfies Record<string, readonly (readonly [string, Record<string, string>])[]>

export type IconName = keyof typeof HUGEICONS
`,
)
console.log(`Wrote ${NAMES.length} icons to src/ko-icons.ts`)
