#!/usr/bin/env ruby
# Writes _data/takumi_commands.yml from the ABOUT blocks in a Takumi checkout,
# for the command reference at /takumi/docs/commands/.
#
#   ruby scripts/takumi-commands.rb "/path/to/Takumi OS"
#
# Commands marked `hidden: yes` (internal helpers the Palette calls) are left out.
require "yaml"

root = ARGV[0] or abort "usage: ruby scripts/takumi-commands.rb <takumi checkout>"
groups = File.readlines(File.join(root, "commands/groups.tsv"), chomp: true, encoding: "UTF-8")
  .reject(&:empty?).map { |l| l.split("\t", 2) }

out = groups.map do |group, about|
  dir = File.join(root, "commands", group)
  next unless Dir.exist?(dir)
  cmds = Dir.children(dir).sort.filter_map do |name|
    path = File.join(dir, name)
    next unless File.file?(path)
    block = File.read(path, encoding: "UTF-8")[/^: <<'ABOUT'\n(.*?)^ABOUT$/m, 1] or next
    c = { "name" => name, "examples" => [] }
    block.each_line(chomp: true) do |line|
      key, value = line.split(":", 2)
      next unless value
      value = value.strip
      case key
      when "example" then c["examples"] << value
      when "summary", "usage", "risk", "sudo", "hidden" then c[key] = value
      end
    end
    next if c["hidden"] == "yes"
    c.delete("hidden")
    c.delete("examples") if c["examples"].empty?
    c
  end
  { "group" => group, "about" => about, "commands" => cmds } unless cmds.empty?
end.compact

File.open(File.join(__dir__, "../_data/takumi_commands.yml"), "w:UTF-8") { |f| f.write(
  "# Generated by scripts/takumi-commands.rb from Takumi's ABOUT blocks. Don't edit by hand.\n" + out.to_yaml) }
puts "#{out.size} groups, #{out.sum { |g| g['commands'].size }} commands"
